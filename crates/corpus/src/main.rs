//! `cargo corpus --size small|medium|large --out <dir> [--seed N] [--force]`
mod plan;

use clap::{Parser, ValueEnum};
use plan::{Body, Plan, Rng};
use std::io::Write;
use std::path::{Path, PathBuf};

const MARKER: &str = ".beacon-corpus";

#[derive(Clone, Copy, ValueEnum)]
pub enum Size {
    Small,
    Medium,
    Large,
}

#[derive(Parser)]
#[command(about = "Generate the synthetic Beacon project corpus")]
struct Args {
    #[arg(long, value_enum)]
    size: Size,
    #[arg(long)]
    out: PathBuf,
    #[arg(long, default_value_t = 1)]
    seed: u64,
    /// Replace an existing corpus (only dirs carrying the `.beacon-corpus` marker).
    #[arg(long)]
    force: bool,
}

fn prepare(out: &Path, force: bool) -> Result<(), String> {
    let non_empty = out.is_dir() && out.read_dir().map_err(|e| e.to_string())?.next().is_some();
    if out.exists() && !out.is_dir() {
        return Err(format!("{} exists and is not a directory", out.display()));
    }
    if non_empty {
        if !force {
            return Err(format!(
                "{} is not empty (use --force to replace a previous corpus)",
                out.display()
            ));
        }
        if !out.join(MARKER).is_file() {
            return Err(format!(
                "refusing to delete {}: no {MARKER} marker file",
                out.display()
            ));
        }
        std::fs::remove_dir_all(out).map_err(|e| e.to_string())?;
    }
    std::fs::create_dir_all(out).map_err(|e| e.to_string())
}

pub fn write(plan: &Plan, out: &Path) -> std::io::Result<()> {
    std::fs::write(out.join(MARKER), "generated by beacon-corpus\n")?;
    for f in &plan.files {
        let path = out.join(&f.path); // '/' separators work on Windows too
        std::fs::create_dir_all(path.parent().expect("file has a parent"))?;
        match &f.body {
            Body::Text(t) => std::fs::write(path, t)?,
            Body::Bin { magic, len, seed } => {
                let mut w = std::io::BufWriter::new(std::fs::File::create(path)?);
                let mut rng = Rng::new(*seed);
                let n = (*len as usize).max(magic.len());
                w.write_all(magic)?;
                let mut left = n - magic.len();
                while left > 0 {
                    let b = rng.next().to_le_bytes();
                    let k = left.min(8);
                    w.write_all(&b[..k])?;
                    left -= k;
                }
                w.flush()?;
            }
        }
    }
    Ok(())
}

fn main() {
    let args = Args::parse();
    if let Err(e) = prepare(&args.out, args.force) {
        eprintln!("error: {e}");
        std::process::exit(1);
    }
    let plan = plan::plan(args.size, args.seed);
    if let Err(e) = write(&plan, &args.out) {
        eprintln!("error: {e}");
        std::process::exit(1);
    }
    let s = plan.stats();
    println!(
        "corpus written to {}\n  files: {}\n  bytes: {} ({:.1} MB binary)\n  script LOC: {}\n  modules: {}\n  generators: {}",
        args.out.display(),
        s.files,
        s.bytes,
        s.binary_bytes as f64 / 1e6,
        s.loc,
        s.modules,
        s.generators
    );
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeMap;

    fn tree(dir: &Path) -> BTreeMap<String, Vec<u8>> {
        let mut m = BTreeMap::new();
        let mut stack = vec![dir.to_path_buf()];
        while let Some(d) = stack.pop() {
            for e in std::fs::read_dir(d).unwrap() {
                let p = e.unwrap().path();
                if p.is_dir() {
                    stack.push(p);
                } else {
                    let rel = p
                        .strip_prefix(dir)
                        .unwrap()
                        .to_string_lossy()
                        .replace(std::path::MAIN_SEPARATOR, "/");
                    m.insert(rel, std::fs::read(&p).unwrap());
                }
            }
        }
        m
    }

    #[test]
    fn small_is_deterministic_and_matches_plan() {
        let (a, b) = (tempfile::tempdir().unwrap(), tempfile::tempdir().unwrap());
        for d in [&a, &b] {
            write(&plan::plan(Size::Small, 7), d.path()).unwrap();
        }
        let (ta, tb) = (tree(a.path()), tree(b.path()));
        assert_eq!(ta, tb);
        assert_eq!(ta.len(), plan::plan(Size::Small, 7).stats().files + 1); // + marker
        assert!(ta.keys().any(|k| k.ends_with(".gen.ts")));
        assert!(ta.contains_key("config.json"));
        let c = tempfile::tempdir().unwrap();
        write(&plan::plan(Size::Small, 8), c.path()).unwrap();
        assert_ne!(ta, tree(c.path()));
    }

    #[test]
    fn large_plan_hits_targets() {
        let s = plan::plan(Size::Large, 1).stats();
        let near = |v: f64, t: f64| (v - t).abs() <= t * 0.1;
        assert!(near(s.files as f64, 3000.0), "files {}", s.files);
        assert!(
            near(s.binary_bytes as f64, 60e6),
            "bytes {}",
            s.binary_bytes
        );
        assert!(near(s.loc as f64, 20000.0), "loc {}", s.loc);
        let gen_share = s.generators as f64 / s.modules as f64;
        assert!((0.1..0.2).contains(&gen_share), "gen share {gen_share}");
    }

    #[test]
    fn force_only_deletes_marked_dirs() {
        let d = tempfile::tempdir().unwrap();
        std::fs::write(d.path().join("precious.txt"), "x").unwrap();
        assert!(prepare(d.path(), false).is_err());
        assert!(prepare(d.path(), true).is_err());
        assert!(d.path().join("precious.txt").exists());
        std::fs::write(d.path().join(MARKER), "").unwrap();
        prepare(d.path(), true).unwrap();
        assert!(!d.path().join("precious.txt").exists());
    }
}
