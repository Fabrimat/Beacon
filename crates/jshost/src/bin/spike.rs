//! Phase-0 QuickJS spike: measures the representative generators and writes docs/spikes/quickjs.md.

use beacon_jshost::{Evaluator, Files, Limits, QuickJs, mem::private_bytes, strip_ts};
use std::fmt::Write;
use std::time::Instant;

const RUNS: usize = 50;
const MB: f64 = 1024.0 * 1024.0;

macro_rules! gen_src {
    ($f:literal) => {
        include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/spike/", $f))
    };
}

fn pct(v: &mut [f64], p: f64) -> f64 {
    v.sort_by(f64::total_cmp);
    v[((v.len() as f64 * p).ceil() as usize).clamp(1, v.len()) - 1]
}

fn time_ms<T>(mut f: impl FnMut() -> T) -> (f64, f64) {
    let mut v: Vec<f64> = (0..RUNS)
        .map(|_| {
            let t = Instant::now();
            std::hint::black_box(f());
            t.elapsed().as_secs_f64() * 1e3
        })
        .collect();
    (pct(&mut v, 0.5), pct(&mut v, 0.95))
}

fn main() {
    let mut md = String::new();
    let rss0 = private_bytes();
    let js = QuickJs::new(Limits::default()).unwrap();
    let rss_rt = private_bytes();

    // Per-context cost: hold 50 fresh, empty contexts.
    let before = private_bytes();
    let held: Vec<_> = (0..50).map(|_| js.context().unwrap()).collect();
    let per_ctx = (private_bytes() - before) as f64 / 50.0;
    drop(held);
    let (ctx_p50, ctx_p95) = time_ms(|| js.context().unwrap());

    let assets: Vec<String> = (0..300)
        .map(|i| format!("sounds/pack{}/s{i}.ogg", i % 10))
        .collect();
    let gens: [(&str, &str, &str); 4] = [
        (
            "sounds (300 .ogg glob)",
            "sounds.gen.ts",
            gen_src!("sounds.gen.ts"),
        ),
        (
            "entities (500, JSON template + deep merge)",
            "entities.gen.ts",
            gen_src!("entities.gen.ts"),
        ),
        (
            "items (2,000, lang + texture registry)",
            "items.gen.ts",
            gen_src!("items.gen.ts"),
        ),
        (
            "car (single content file)",
            "car.gen.ts",
            gen_src!("car.gen.ts"),
        ),
    ];
    let mut files = Files::from([(
        "entity.template.json".to_string(),
        gen_src!("entity.template.json").to_string(),
    )]);
    for (_, name, src) in gens {
        files.insert(name.to_string(), src.to_string());
    }

    let mut rows = String::new();
    let mut worst_eval = 0.0f64;
    let mut rss_peak = 0;
    for (label, name, src) in gens {
        let (s50, s95) = time_ms(|| strip_ts(name, src).unwrap());
        let out = js.eval(name, &files, &assets).unwrap();
        rss_peak = rss_peak.max(private_bytes());
        let size = serde_json::to_vec(&out.items).unwrap().len();
        let (e50, e95) = time_ms(|| js.eval(name, &files, &assets).unwrap());
        worst_eval = worst_eval.max(e95);
        writeln!(
            rows,
            "| {label} | {} | {s50:.2} / {s95:.2} | {e50:.2} / {e95:.2} | {:.1} KiB | {} |",
            out.items.len(),
            size as f64 / 1024.0,
            out.uncacheable
        )
        .unwrap();
    }
    let rss_end = private_bytes();
    let exe = std::env::current_exe().unwrap();
    let bin_mb = std::fs::metadata(&exe).unwrap().len() as f64 / MB;
    let cpu = std::env::var("PROCESSOR_IDENTIFIER").unwrap_or_else(|_| "unknown".into());
    let cores = std::thread::available_parallelism().map_or(0, |n| n.get());
    let verdict = |ok: bool| if ok { "within budget" } else { "OVER budget" };

    writeln!(
        md,
        "# QuickJS spike (phase 0)\n\n\
Generated by `cargo spike` (`crates/jshost/src/bin/spike.rs`); do not edit by hand.\n\n\
Machine: {} / {}, {cores} logical cores, CPU `{cpu}`. Release build, QuickJS via rquickjs 0.14, TS via oxc 0.146.\n\
Memory = private bytes (Windows PrivateUsage = committed private memory, which can read lower than task-manager working set) or RSS (`ps`) elsewhere, this process only.\n\n\
## Generators ({RUNS} runs each, one fresh context per run)\n\n\
Eval time includes module loading, TS strip of every imported `.ts`, running, and JSON serialisation of the items; \
the context-creation time is part of it. The sound generator sees a synthetic 300-file asset list.\n\n\
| Generator | Items | TS strip p50 / p95 (ms) | Eval p50 / p95 (ms) | Output JSON | Uncacheable |\n|---|---|---|---|---|---|\n{rows}\n\
Bare context creation (`Context::full`): p50 {ctx_p50:.3} ms, p95 {ctx_p95:.3} ms.\n\n\
## Memory\n\n\
| Point | Private bytes |\n|---|---|\n\
| Process start | {:.1} MB |\n\
| After creating the runtime | {:.1} MB (+{:.2} MB) |\n\
| Per empty context (mean of 50 held at once) | {:.0} KiB |\n\
| Highest sample after a generator eval (heaviest: 2,000 items) | {:.1} MB |\n\
| After all runs, runtime idle | {:.1} MB |\n\n\
Release binary `spike`: {bin_mb:.1} MB (includes oxc and the spike harness).\n\n\
## Reading against ARCHITECTURE 12\n\n\
| Budget | Measured | Reading |\n|---|---|---|\n\
| Watch TS change p95 < 300 ms | worst generator eval p95 {worst_eval:.1} ms (JS-host share only) | {} |\n\
| Idle RSS (`watch`) < 40 MB | runtime alone {:.1} MB; contexts are dropped after each eval | {} |\n\
| Peak build RSS < 150 MB | {:.1} MB highest sample with the heaviest generator | {} |\n\
| Binary < 30 MB | {bin_mb:.1} MB | {} |\n\n\
**Measured**: everything in the tables above, on synthetic generators modelled on the production patterns of 2.2 \
(pure data building, one-to-many). **Extrapolated / not measured**: the rest of the TS-change path (file watch, VFS, \
routing, writes, esbuild pre-bundle), real generators from the production projects, the Defender-enabled CI \
machine, process-tree RSS with the esbuild sidecar, and macOS numbers. The JS-host share of the 300 ms / 150 MB budgets \
is what the spike can speak to.\n\n\
**Go/no-go**: {}\n",
        std::env::consts::OS,
        std::env::consts::ARCH,
        rss0 as f64 / MB,
        rss_rt as f64 / MB,
        (rss_rt - rss0) as f64 / MB,
        per_ctx / 1024.0,
        rss_peak as f64 / MB,
        rss_end as f64 / MB,
        verdict(worst_eval < 300.0),
        rss_end as f64 / MB,
        verdict(rss_end < 40 << 20),
        rss_peak as f64 / MB,
        verdict(rss_peak < 150 << 20),
        verdict(bin_mb < 30.0),
        if worst_eval < 300.0 && rss_peak < 150 << 20 && bin_mb < 30.0 {
            "GO on QuickJS for the JS host; the V8 fallback (11.2) is not needed on these numbers."
        } else {
            "NO-GO as measured: see the over-budget rows and consider the V8 fallback (11.2)."
        }
    )
    .unwrap();

    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/spikes/quickjs.md");
    std::fs::create_dir_all(std::path::Path::new(path).parent().unwrap()).unwrap();
    std::fs::write(path, &md).unwrap();
    print!("{md}");
}
