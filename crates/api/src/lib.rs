use beacon_engine::diag::{Code, Diagnostic};
use beacon_fetch::{Confirm, FetchError, Pinned};
use std::collections::BTreeMap;
use std::io::Write;
use std::path::{Path, PathBuf};

const VANILLA: &str = "@minecraft/vanilla-data";
const SCHEMAS: &str = "@minecraft/bedrock-schemas";
const ITEM_COMPONENTS: &str = "types/bp/items/components/";
/// (file kind, schema file whose `properties` are the component names). Items are not in the
/// schemas; their names come from `ITEM_COMPONENTS`.
const COMPONENT_SCHEMAS: &[(&str, &str)] = &[
    (
        "entity",
        "schemas/bp/entities/entity_entity_component_definitions.schema.json",
    ),
    ("block", "schemas/bp/blocks/block_components.schema.json"),
    (
        "biome",
        "schemas/bp/biomes/biome_biome_components.schema.json",
    ),
];

/// Packages of one supported game version.
#[derive(Debug, Clone, Copy)]
pub struct VersionPins {
    /// `1.26.50`: matched against a target's `targetVersion` (major.minor.patch; a
    /// `targetVersion` without pins uses the newest pinned version not above it).
    pub game_version: &'static str,
    /// (npm package, version, tarball pin).
    pub packages: &'static [(&'static str, &'static str, Pinned)],
}

macro_rules! pin {
    ($pkg:literal, $name:literal, $ver:literal, $size:literal, $hash:literal) => {
        (
            concat!("@minecraft/", $pkg),
            $ver,
            Pinned {
                url: concat!(
                    "https://registry.npmjs.org/@minecraft/",
                    $pkg,
                    "/-/",
                    $name,
                    "-",
                    $ver,
                    ".tgz"
                ),
                blake3: $hash,
                size: $size,
            },
        )
    };
}

