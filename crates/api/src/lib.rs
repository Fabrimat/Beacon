/// The index for `game_version`: the cached one when present and current
/// (`ApiIndex::load`), else downloads (per `confirm`), builds, writes the cache atomically
/// and returns its path. Errors are `DownloadNeedsConfirm` / `DownloadFailed` /
/// `DownloadHashMismatch` / `ApiIndexMissing` (no pins for that version) diagnostics.
pub fn ensure(game_version: &str, confirm: Confirm) -> Result<PathBuf, Diagnostic> {
    let Some(vp) = PINS.iter().find(|p| p.game_version == game_version) else {
        return Err(Diagnostic::new(
            Code::ApiIndexMissing,
            format!("no API pins for game version {game_version}"),
        ));
    };
    let tools = beacon_fetch::default_dir()
        .ok_or_else(|| Diagnostic::new(Code::DownloadFailed, "no user data directory"))?;
    ensure_with(vp, &tools, confirm)
}

/// [`ensure`] for explicit pins and a download cache dir (tests seed `tools` offline).
pub fn ensure_with(
    vp: &VersionPins,
    tools: &Path,
    confirm: Confirm,
) -> Result<PathBuf, Diagnostic> {
    let path = cache_path(vp.game_version).ok_or_else(|| {
        Diagnostic::new(
            Code::DownloadFailed,
            format!(
                "bad game version {:?} or no data directory",
                vp.game_version
            ),
        )
    })?;
    if ApiIndex::load(vp.game_version).is_ok() {
        return Ok(path);
    }
    let mut files = Vec::new();
    for (pkg, ver, pin) in vp.packages {
        let f = beacon_fetch::fetch(pin, tools, confirm).map_err(|e| match e {
            FetchError::NeedsConfirm => Diagnostic::new(
                Code::DownloadNeedsConfirm,
                format!(
                    "the API index for {} needs {pkg}@{ver} from {} ({} bytes, blake3-pinned); \
                     pass --yes or set BEACON_DOWNLOAD=yes to allow it",
                    vp.game_version, pin.url, pin.size
                ),
            ),
            FetchError::HashMismatch { .. } => {
                Diagnostic::new(Code::DownloadHashMismatch, format!("{pkg}@{ver}: {e}"))
            }
            e => Diagnostic::new(Code::DownloadFailed, e.to_string()),
        })?;
        let bytes = std::fs::read(&f)
            .map_err(|e| Diagnostic::new(Code::DownloadFailed, format!("{}: {e}", f.display())))?;
        files.push((*pkg, *ver, pin.blake3, bytes));
    }
    let tarballs: Vec<Tarball> = files
        .iter()
        .map(|(p, v, h, b)| (*p, *v, *h, b.as_slice()))
        .collect();
    let index = build(vp.game_version, &tarballs)?;
    write_cache(&path, &index)
        .map_err(|e| Diagnostic::new(Code::DownloadFailed, format!("{}: {e}", path.display())))?;
    Ok(path)
}

/// Canonical bytes of `index.json`: compact JSON over sorted maps, so equal inputs give
/// byte-identical output.
pub fn to_json(index: &ApiIndex) -> Vec<u8> {
    serde_json::to_vec(index).expect("ApiIndex serializes")
}

fn write_cache(path: &Path, index: &ApiIndex) -> std::io::Result<()> {
    let dir = path.parent().expect("cache path has a parent");
    std::fs::create_dir_all(dir)?;
    let mut tmp = tempfile::NamedTempFile::new_in(dir)?; // removed on any error
    tmp.write_all(&to_json(index))?;
    tmp.persist(path).map_err(|e| e.error)?;
    Ok(())
}

/// (npm package, version, expected blake3 hex, tarball bytes).
pub type Tarball<'a> = (&'a str, &'a str, &'a str, &'a [u8]);

/// Builds the index from already-downloaded tarballs (tests use local fixtures). Each is
/// refused (`DownloadHashMismatch`) unless its blake3 equals the expected one, and
/// (`DownloadFailed`) unless its `package.json` names the same package and version and has
/// `"license": "MIT"`.
pub fn build(game_version: &str, tarballs: &[Tarball]) -> Result<ApiIndex, Diagnostic> {
    let mut ix = ApiIndex {
        schema: API_INDEX_SCHEMA,
        game_version: game_version.to_string(),
        sources: Vec::new(),
        script_modules: BTreeMap::new(),
        vanilla: BTreeMap::new(),
        components: BTreeMap::new(),
    };
    for &(pkg, ver, want, bytes) in tarballs {
        let fail = |m: String| Diagnostic::new(Code::DownloadFailed, format!("{pkg}@{ver}: {m}"));
        let actual = blake3::hash(bytes).to_hex().to_string();
        if actual != want {
            return Err(Diagnostic::new(
                Code::DownloadHashMismatch,
                format!("{pkg}@{ver}: hash mismatch: expected {want}, got {actual}"),
            ));
        }
        let files = pack::read(bytes, &|p| wanted(pkg, p)).map_err(&fail)?;
        let manifest: serde_json::Value = files
            .get("package.json")
            .and_then(|b| serde_json::from_slice(b).ok())
            .ok_or_else(|| fail("no readable package.json".into()))?;
        let field = |k: &str| manifest.get(k).and_then(|v| v.as_str());
        let license = field("license").unwrap_or("<none>");
        if license != "MIT" {
            return Err(fail(format!(
                "package.json license is {license:?}, only MIT packages are used"
            )));
        }
        if field("name") != Some(pkg) || field("version") != Some(ver) {
            return Err(fail(format!(
                "package.json is {:?}@{:?}",
                field("name").unwrap_or("?"),
                field("version").unwrap_or("?")
            )));
        }
        let text = |p: &str| -> Result<&str, Diagnostic> {
            let b = files.get(p).map_or(&[][..], |b| b.as_slice());
            std::str::from_utf8(b).map_err(|_| fail(format!("{p}: not UTF-8")))
        };
        if pkg == VANILLA {
            for (name, b) in &files {
                let Some(stem) = name
                    .strip_prefix("lib/mojang-")
                    .and_then(|n| n.strip_suffix(".d.ts"))
                else {
                    continue;
                };
                let src = std::str::from_utf8(b).map_err(|_| fail(format!("{name}: not UTF-8")))?;
                let ids = ix.vanilla.entry(snake(stem)).or_default();
                for e in dts::parse(src, name).map_err(&fail)? {
                    ids.extend(e.enum_values);
                }
            }
            ix.vanilla.retain(|_, ids| !ids.is_empty());
        } else if pkg == SCHEMAS {
            for (kind, file) in COMPONENT_SCHEMAS {
                if files.contains_key(*file) {
                    let names =
                        schema_components(text(file)?).map_err(|e| fail(format!("{file}: {e}")))?;
                    ix.components
                        .entry(kind.to_string())
                        .or_default()
                        .extend(names);
                }
            }
            let items = ix.components.entry("item".into()).or_default();
            for (name, _) in files.iter().filter(|(n, _)| n.starts_with(ITEM_COMPONENTS)) {
                if let Some((n, c)) = item_component(text(name)?) {
                    items.entry(n).or_insert(c);
                }
            }
            ix.components.retain(|_, c| !c.is_empty());
            if ix.components.is_empty() {
                return Err(fail("no component names found in the schemas".into()));
            }
        } else {
            let entry = field("types")
                .map(|t| t.trim_start_matches("./").to_string())
                .unwrap_or_else(|| "index.d.ts".into());
            let mut exports = BTreeMap::new();
            for e in dts::parse(text(&entry)?, &entry).map_err(&fail)? {
                exports.entry(e.name).or_insert(e.item);
            }
            if exports.is_empty() {
                return Err(fail(format!("{entry}: no exports found")));
            }
            ix.script_modules
                .entry(pkg.to_string())
                .or_default()
                .push(ScriptModule {
                    version: manifest_version(ver),
                    beta: ver.contains("-beta"),
                    exports,
                });
        }
        ix.sources.push(Provenance {
            package: pkg.to_string(),
            version: ver.to_string(),
            blake3: actual,
            license: license.to_string(),
        });
    }
    ix.sources
        .sort_by(|a, b| (&a.package, &a.version).cmp(&(&b.package, &b.version)));
    for v in ix.script_modules.values_mut() {
        v.sort_by(|a, b| (a.beta, &a.version).cmp(&(b.beta, &b.version)));
    }
    Ok(ix)
}

/// Members worth reading from a package's tarball.
fn wanted(pkg: &str, p: &str) -> bool {
    p == "package.json"
        || match pkg {
            VANILLA => p.starts_with("lib/mojang-") && p.ends_with(".d.ts"),
            SCHEMAS => {
                COMPONENT_SCHEMAS.iter().any(|(_, f)| *f == p)
                    || (p.starts_with(ITEM_COMPONENTS) && p.ends_with(".d.ts"))
            }
            _ => p.ends_with(".d.ts") && !p.starts_with("node_modules/"),
        }
}

/// npm `2.11.0-beta.1.26.50-stable` -> manifest dependency version `2.11.0-beta`.
fn manifest_version(npm: &str) -> String {
    match npm.find("-beta") {
        Some(i) => format!("{}-beta", &npm[..i]),
        None => npm.to_string(),
    }
}

/// `mojang-cameraPresets.d.ts` stem `cameraPresets` -> `camera_presets`.
fn snake(s: &str) -> String {
    let mut o = String::new();
    for c in s.chars() {
        if c.is_ascii_uppercase() {
            o.push('_');
        }
        o.push(c.to_ascii_lowercase());
    }
    o
}

/// `properties` keys (`minecraft:*`) of a component registry schema, with their descriptions.
fn schema_components(json: &str) -> Result<BTreeMap<String, Component>, String> {
    let v: serde_json::Value = serde_json::from_str(json).map_err(|e| e.to_string())?;
    let props = v
        .get("properties")
        .and_then(|p| p.as_object())
        .ok_or("no properties")?;
    Ok(props
        .iter()
        .filter(|(k, _)| k.starts_with("minecraft:"))
        .map(|(k, p)| {
            let description = p
                .get("description")
                .and_then(|d| d.as_str())
                .map(str::to_string);
            (
                k.clone(),
                Component {
                    description,
                    experimental: None,
                },
            )
        })
        .collect())
}

/// An item component `.d.ts` documents itself as ` * Allow Off Hand (minecraft:allow_off_hand)`
/// followed by its description lines.
fn item_component(src: &str) -> Option<(String, Component)> {
    let mut lines = src.lines().map(|l| l.trim().trim_start_matches('*').trim());
    let name = lines.find_map(|l| {
        let i = l.find("(minecraft:")?;
        let rest = &l[i + 1..];
        Some(rest[..rest.find(')')?].to_string())
    })?;
    let desc: Vec<&str> = lines
        .take_while(|l| !l.is_empty() && !l.starts_with('@') && !l.starts_with("NOTE"))
        .collect();
    let description = (!desc.is_empty()).then(|| desc.join(" "));
    Some((
        name,
        Component {
            description,
            experimental: None,
        },
    ))
}
